"""A session refinement reads the text the session page shows, and keeps its result until the conversation changes.

The refinement used to read the raw records (runtime envelopes and meta records of Claude Code and Codex
went to the model) and hashed them with the capture time and the record file's size, so appended tool
logs or a re-sync counted as a changed conversation. It now reads the visible user and assistant text,
and the hash covers only the session's identity, its coverage and the messages in order.
"""
from __future__ import annotations

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

from memorive.sessions.controller import SessionsProductController


ATTEMPT_ROOT = Path(__file__).resolve().parents[1]
SESSION_ID = "11111111-2222-4333-8444-555555555540"


class _Service:
    def call(self, method: str, params: dict[str, object]) -> dict[str, object]:
        if method == "settings.get_state":
            return {"api_profiles": []}
        return {}


def _append(path: Path, rows: list[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows))


def _record(kind: str, text: str, minute: int, **extra: object) -> dict[str, object]:
    at = (datetime.now(timezone.utc) - timedelta(hours=1) + timedelta(minutes=minute)).strftime("%Y-%m-%dT%H:%M:%SZ")
    return {"type": kind, "timestamp": at, "sessionId": SESSION_ID, "cwd": "D:\\work",
            "message": {"role": kind, "content": text}, **extra}


def test_refinement_reads_visible_text_and_keeps_its_hash_for_tool_logs(tmp_path: Path) -> None:
    record = tmp_path / "claude-home" / "projects" / "D--work" / f"{SESSION_ID}.jsonl"
    _append(record, [
        _record("user", "<local-command-caveat>Caveat: generated by local commands.</local-command-caveat>", 0,
                isMeta=True),
        _record("user", "<system-reminder>injected context</system-reminder>\n请整理会议结论", 1),
        _record("assistant", "结论是 A，下周复核。", 2),
    ])
    (tmp_path / "codex-home").mkdir()
    controller = SessionsProductController(
        _Service(), object(), ATTEMPT_ROOT / "contracts" / "analysis", ATTEMPT_ROOT / "fixtures_t08",
        tmp_path / "state",
        source_roots={"codex_home": tmp_path / "codex-home", "claude_home": tmp_path / "claude-home"},
    )
    controller.call("sessions.refresh", {})
    projection_id = controller.call("sessions.list", {"source": "claude"})["rows"][0]["local_projection_id"]

    _row, messages, _source, first = controller._refinement_input(projection_id)
    assert messages == [{"role": "user", "content": "请整理会议结论"},
                        {"role": "assistant", "content": "结论是 A，下周复核。"}]

    # Tool logs appended later, then a re-sync: the same conversation, the same hash.
    _append(record, [{"type": "system", "timestamp": "2026-11-22T23:00:00Z", "sessionId": SESSION_ID,
                      "content": "tool finished"}])
    controller.call("sessions.refresh", {})
    assert controller._refinement_input(projection_id)[3] == first

    # New conversation: a new hash.
    _append(record, [_record("user", "再补充一点", 3)])
    assert controller._refinement_input(projection_id)[3] != first
