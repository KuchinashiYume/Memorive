def _jsonable(value: Any) -> Any:
    if is_dataclass(value):
        return {key: _jsonable(item) for key, item in asdict(value).items()}
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [_jsonable(item) for item in value]
    return value


def _canonical_bytes(value: Any) -> bytes:
    return json.dumps(
        _jsonable(value),
        ensure_ascii=False,
        allow_nan=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")


def _validate_context_pack_language(artifact: Mapping[str, Any], *, source_text: str, source_language: str) -> None:
    # Only exact built-in retrieval vocabulary is metadata. Preserve the saved
    # pack and its hash; source blocks and every other field remain checked.
    from retrieval.structured_context import _FACET_SPECS
    content = _jsonable(artifact)
    for facet in content.get("pack", {}).get("query_facets", []):
        spec = _FACET_SPECS.get(facet.get("id"))
        if spec and facet.get("query_terms") == list(spec["terms"]):
            facet["query_terms"] = []
    validate_generated_language(
        source_text=source_text,
        generated_text=_canonical_bytes(content).decode("utf-8"),
        source_language=source_language,
        artifact_name="ContextPack",
    )


def _validate_judgment_language(judgment: Mapping[str, Any], *, source_text: str, source_language: str) -> None:
    # debt.path is a local ledger locator generated by this application, not
    # model prose. A Chinese Windows directory must not invalidate an English
    # review. Keep the original locator in the saved artifact and validate all
    # remaining review content, including pending status and dispute text.
    content = deepcopy(judgment)
    if isinstance(content.get("debt"), dict):
        content["debt"].pop("path", None)
    validate_generated_language(
        source_text=source_text,
        generated_text=_canonical_bytes(content).decode("utf-8"),
        source_language=source_language,
        artifact_name="Judgment.json",
    )


def _validate_artifact_language(path: Path, *, artifact_kind: str, source_text: str, source_language: str) -> None:
    text = path.read_text(encoding="utf-8")
    if artifact_kind == "CORE_CONTEXT_PACK":
        _validate_context_pack_language(json.loads(text), source_text=source_text, source_language=source_language)
    elif artifact_kind == "CORE_JUDGMENT_REVIEW":
        _validate_judgment_language(json.loads(text), source_text=source_text, source_language=source_language)
    else:
        if artifact_kind == "CORE_CARD":
            # Omission tombstones retain the exact removed value, including old
            # application-generated warnings. Exempt only those two known
            # warning values at the audit metadata path. Scientific values,
            # quotes, reasons and all other prose still pass the source guard;
            # neither the Card bytes nor its historical evidence are rewritten.
            import re
            import yaml
            from evidence_extraction.card import DANGER_UNKNOWN_KD, DANGER_UNKNOWN_FIELD
            fences = list(re.finditer(r"(?m)^---[ \t]*\r?$", text))
            if len(fences) >= 2 and fences[0].start() == 0:
                content = yaml.safe_load(text[fences[0].end():fences[1].start()])
                if isinstance(content, dict):
                    for omission in content.get("omissions") or []:
                        removed = omission.get("removed_value") if isinstance(omission, dict) else None
                        if isinstance(removed, dict) and removed.get("danger") in (DANGER_UNKNOWN_KD, DANGER_UNKNOWN_FIELD):
                            removed["danger"] = "Legacy application verification warning (original preserved)."
                    text = _canonical_bytes(content).decode("utf-8") + text[fences[1].end():]
        validate_generated_language(
            source_text=source_text, generated_text=text,
            source_language=source_language, artifact_name=artifact_kind,
        )


def _atomic_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.parent / f".{path.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp"
    with temporary.open("xb") as stream:
        stream.write(_canonical_bytes(value) + b"\n")
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


def _atomic_pickle(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.parent / f".{path.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp"
    with temporary.open("xb") as stream:
        pickle.dump(value, stream, protocol=pickle.HIGHEST_PROTOCOL)
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


