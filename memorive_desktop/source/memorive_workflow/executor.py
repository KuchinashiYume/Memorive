def render_human_review(
    *,
    title: str,
    paper_id: str,
    source_sha256: str,
    question: str,
    analysis: Any,
    judgment: Mapping[str, Any],
    source_language: str,
    synthetic: bool,
) -> str:
    """Render the human-review artifact without changing the document language."""

    labels = _review_labels(source_language)
    disputes = [row for row in judgment.get("rulings", []) if row.get("agrees") is False]
    omissions = judgment.get("omissions") or []
    prior_review_qualifications = tuple(getattr(analysis, "review_limitations", ()) or ())
    lines = [
        f"# {labels['title']}: {title}",
        "",
        f"- paper_id: `{paper_id}`",
        f"- {labels['input_sha']}: `{source_sha256}`",
        f"- {labels['question']}: {question}",
        f"- {labels['model']}: `{analysis.analysis_model}`",
        f"- {labels['trace']}: {judgment.get('trace_resolved')}/{judgment.get('trace_total')}",
        f"- {labels['rulings']}: {len(judgment.get('rulings') or [])}",
        f"- {labels['pending']}: {len(judgment.get('deferred') or []) + len(disputes) + len(omissions) + len(prior_review_qualifications)}",
        "",
        f"## {labels['draft']}",
        "",
        analysis.render(language=source_language),
        "",
        f"## {labels['boundary']}",
        "",
        labels["boundary_text"],
    ]
    if judgment.get("execution_status") == "SKIPPED":
        notice = {
            "zh": "核对分析已按设置跳过；尚未核验分析结论，须人工审核。",
            "en": "Analysis cross-check was disabled. The analysis remains unverified and requires human review.",
            "ja": "設定により分析の照合をスキップしました。分析結果は未検証であり、人による確認が必要です。",
        }[source_language]
        lines.extend(["", notice])
    if disputes:
        heading = {"zh": "待核对的审核异议", "en": "Review findings requiring human attention", "ja": "人による確認が必要なレビュー指摘"}[source_language]
        lines.extend(["", "## " + heading, ""])
        for row in disputes:
            lines.append(f"- [{row.get('i')}] {row.get('conclusion', '')}")
            lines.extend("  - " + str(item.get("detail", "")) for item in row.get("disputes", []))
    if omissions:
        from .analysis_omission import omission_notice
        lines.append(omission_notice(omissions, source_language))
    if synthetic:
        lines.append(labels["synthetic"])
    lines.append("")
    return "\n".join(lines)


